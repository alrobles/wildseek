"""Seed a minimal app/data for a fresh clone so docker compose demos
something real: JSONs + catalog tables + top-100 risk, NO suit PNGs.

Run from repo root:
    python pipeline/seed_demo.py
    cd serve && docker compose up

Produces app/data.sample/ — copy or symlink it to app/data/.
"""
import json
import shutil
import sys
from pathlib import Path

SRC = Path("app/data")           # full export lives here on the lab box
DST = Path("app/data.sample")    # tiny, committable demo set


def main():
    if not SRC.exists():
        sys.exit(f"{SRC} missing — run pipeline/export_serve.py first")
    DST.mkdir(parents=True, exist_ok=True)

    # --- always copy (small, required) --------------------------------
    keep = ["meta.json", "metrics.json", "we_called_it.json",
            "briefing.json", "qa_report.json",
            "species_winner.csv",
            "decisions_delta.csv", "decisions_all.jsonl",
            "risk.png", "risk_detect.png"]
    for name in keep:
        p = SRC / name
        if p.exists():
            shutil.copy2(p, DST / name)

    # --- top-100 risk + susceptibility --------------------------------
    import pandas as pd
    for name in ("risk_watershed.parquet", "susceptibility.parquet"):
        p = SRC / name
        if not p.exists():
            continue
        df = pd.read_parquet(p)
        col = "risk" if "risk" in df.columns else "p_host"
        df.nlargest(100, col).to_parquet(DST / name, index=False)

    # --- heavy layers: subsample to the demo species set ---------------
    sus = DST / "susceptibility.parquet"
    keys = (pd.read_parquet(sus)["specieskey"].tolist()
            if sus.exists() else [])
    fc = SRC / "fit_catalog.csv"
    if fc.exists() and keys:
        cat = pd.read_csv(fc)
        cat[cat.specieskey.isin(keys)].to_csv(
            DST / "fit_catalog.csv", index=False)
    def _round_coords(o):
        if isinstance(o, list):
            return ([_round_coords(v) for v in o] if
                    o and isinstance(o[0], list) else
                    [round(v, 2) if isinstance(v, float) else v for v in o])
        return o

    for name, feat_cap in (("detections.geojson", 2000),
                           ("county_exposure.geojson", None)):
        p = SRC / name
        if not p.exists():
            continue
        gj = json.loads(p.read_text())
        feats = gj.get("features", [])
        if feat_cap and len(feats) > feat_cap:
            feats = feats[:feat_cap]
        for ft in feats:
            geom = ft.get("geometry")
            if geom:
                geom["coordinates"] = _round_coords(geom["coordinates"])
        (DST / name).write_text(json.dumps(
            {"type": "FeatureCollection", "features": feats}))

    # --- a couple of explain cards so /explain has content -------------
    for p in sorted(SRC.glob("explain_*.json"))[:6]:
        shutil.copy2(p, DST / p.name)

    # --- placeholder for missing suit PNGs ------------------------------
    (DST / "NO_SUIT_PNGS.txt").write_text(
        "suit_*.png layers are generated by pipeline/predict_suit.R "
        "on the cluster and are too large for the demo seed. The API "
        "still serves every endpoint; map layer will be empty.\n")

    n = len(list(DST.iterdir()))
    print(f"seeded {DST}: {n} files "
          f"({sum(f.stat().st_size for f in DST.iterdir())/1e6:.1f} MB)")


if __name__ == "__main__":
    main()
